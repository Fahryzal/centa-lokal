import * as BarangjadiInterfaces from '@/pages/master/barang-jadi/interface/BarangjadiInterfaces';
import { filterAndRemoveKeys, ThrowError } from '@/utils/helper';
import api from '@/api/axiosInstance';

export const fetchGenCodeBarangjadi = async () => {
  try {
    const result = await api.get(`/api/v1/master/generate-code/barang`);
    if (![200, 201].includes(result.status)) {
      throw new Error('Terjadi kesalahan');
    }
    return result.data.data;
  } catch (e: any) {
    ThrowError(e);
  }
};

