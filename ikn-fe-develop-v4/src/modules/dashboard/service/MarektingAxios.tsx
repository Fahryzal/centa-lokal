import { filterAndRemoveKeys, ThrowError } from '@/utils/helper';
import api from '@/api/axiosInstance';
import {
  ParamsTypeBuyer,
  ParamsTypeInvoice,
  ParamsTypeMarketing,
  ParamsTypeSalesPlan,
} from '@/modules/dashboard/Components/Marketing/interfaces/Inetrfaces';
import * as BuyerInterfaces from '@/modules/dashboard/Components/Marketing/interfaces/BuyerInterfaces';

export const fetchDataChar = async (params: ParamsTypeMarketing) => {
  const removeKeys = ['data', 'total']; // Properti yang ingin dihapus
  const fixObjParams = filterAndRemoveKeys(params, removeKeys);
  const queryString = new URLSearchParams(fixObjParams as any).toString();
  try {
    const result = await api.get(`api/v1/dashboard/marketing?${queryString}`);
    if (![200, 201].includes(result.status)) {
      throw new Error('Terjadi kesalahan');
    }
    return result.data.data;
  } catch (e: any) {
    ThrowError(e);
  }
};

